local scope=dofile(arg[1]or 'apps/router/root/usr/share/neko-smart/account-scope.lua')
local context=scope.context({lan={['ipv4-address']={{address='192.168.1.1',mask=24}},['ipv6-prefix-assignment']={{address='fd00:db8:1::',mask=64,['local-address']={address='fd00:db8:1::1',mask=64}}}},wan={['ipv4-address']={{address='10.21.1.81',mask=16}}}})
assert(scope.classify('192.168.1.10',context)=='lan')
assert(scope.classify('fd00:db8:1::10',context)=='lan')
assert(scope.classify('192.168.1.1',context)=='router')
assert(scope.classify('10.21.1.81',context)=='router')
assert(scope.classify('10.18.21.175',context)=='upstream')
assert(scope.classify('172.18.0.2',context)=='upstream')
assert(scope.classify('bad',context)=='unknown')
assert(scope.classify('192.168.1.10',{lan_prefixes={}})=='unknown')
local campus_lan=scope.context({lan={['ipv4-address']={{address='10.18.1.1',mask=24}}}})
assert(scope.classify('10.18.1.2',campus_lan)=='lan')
assert(scope.classify('10.18.2.2',campus_lan)=='upstream')
